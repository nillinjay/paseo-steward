'use strict';
const assert = require('node:assert/strict');
const { execFileSync } = require('node:child_process');
const { mkdtempSync, mkdirSync, writeFileSync, readFileSync, rmSync } = require('node:fs');
const { join, resolve } = require('node:path');
const { tmpdir } = require('node:os');
const root = resolve(__dirname, '..');
const temp = mkdtempSync(join(tmpdir(), 'steward-history-'));
const git = (cwd, ...args) => execFileSync('git', args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
try {
  const repo = join(temp, 'repo');
  mkdirSync(repo);
  git(repo, 'init');
  git(repo, 'config', 'user.email', 'check@example.invalid');
  git(repo, 'config', 'user.name', 'Check');
  git(repo, 'commit', '--allow-empty', '-m', 'accepted');
  const accepted = git(repo, 'rev-parse', 'HEAD');
  const worktree = join(temp, 'worker');
  git(repo, 'worktree', 'add', '--detach', worktree, accepted);
  const evidence = { task: 'T-test', commit: accepted, verdict: 'PASS', provenance: { clean: true, commit: accepted }, scope: { pass: true }, gate: { pass: true, commands: [{ cmd: 'true', exit_code: 0 }] } };
  mkdirSync(join(worktree, 'checks/out'), { recursive: true });
  const name = `guard-T-test-${accepted}.json`;
  writeFileSync(join(worktree, 'checks/out', name), JSON.stringify(evidence));
  const retained = execFileSync(join(root, 'tools/keep-artifact.sh'), ['T-test', worktree], { cwd: repo, encoding: 'utf8' }).trim();
  assert.equal(retained, `checks/out/${name}`);
  git(repo, 'worktree', 'remove', '--force', worktree);
  assert.deepEqual(JSON.parse(readFileSync(join(repo, retained), 'utf8')), evidence);
  const bundle = join(temp, 'steward.cjs');
  require('esbuild').buildSync({ entryPoints: [join(root, 'server/steward.ts')], bundle: true, platform: 'node', format: 'cjs', outfile: bundle });
  const { acceptanceState } = require(bundle);
  let row = acceptanceState(repo, accepted)[0];
  assert.equal(row.allCommandsPassed, true);
  assert.equal(row.commitMatchesHead, true);
  console.log('PASS: artifact at HEAD counts; retained copy survives worktree removal');
  git(repo, 'commit', '--allow-empty', '-m', 'later merge');
  const head = git(repo, 'rev-parse', 'HEAD');
  row = acceptanceState(repo, head)[0];
  assert.equal(row.allCommandsPassed, true);
  assert.equal(row.commitMatchesHead, true);
  assert.match(row.verdict, /ancestor.*not HEAD/);
  console.log('PASS: ancestor artifact counts and is annotated');
  const missing = 'f'.repeat(40);
  writeFileSync(join(repo, 'checks/out', `guard-T-missing-${missing}.json`), JSON.stringify({ ...evidence, task: 'T-missing', commit: missing }));
  row = acceptanceState(repo, head).find(entry => entry.task === 'T-missing');
  assert.equal(row.allCommandsPassed, false);
  assert.equal(row.commitMatchesHead, false);
  console.log('PASS: nonexistent commit does not count');
  git(repo, 'checkout', '--orphan', 'unrelated');
  git(repo, 'commit', '--allow-empty', '-m', 'unrelated');
  row = acceptanceState(repo, git(repo, 'rev-parse', 'HEAD')).find(entry => entry.task === 'T-test');
  assert.equal(row.allCommandsPassed, false);
  console.log('PASS: existing commit outside HEAD history does not count');
} finally {
  rmSync(temp, { recursive: true, force: true });
}
